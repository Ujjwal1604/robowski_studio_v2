export function runCardSvg(run: RunResult): string {
  const width = 1200,
    height = 900,
    p: string[] = [],
    visiblePlates = Math.min(run.plates, 9);
  p.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><rect width="100%" height="100%" fill="#f7f7f3"/><rect x="32" y="32" width="1136" height="${
      height - 64
    }" rx="26" fill="#fff" stroke="#d9ddd5" stroke-width="2"/><text x="64" y="87" font-family="Arial,sans-serif" font-size="24" font-weight="700" fill="#315e49">robowski studio</text><text x="64" y="137" font-family="Arial,sans-serif" font-size="38" font-weight="700" fill="#1f2a23">${xmlEsc(
      run.runName
    )}</text><text x="64" y="178" font-family="Arial,sans-serif" font-size="20" fill="#435047">${
      ({ equivalence: 'Equivalence', triplet: 'Triplet plate' } as any)[run.modeLabel || run.mode] ||
      'Concentration'
    } mode · ${run.vialVolume} µL per vial · Robowski ${run.hood}</text><text x="64" y="225" font-family="Arial,sans-serif" font-size="16" fill="#435047">${
      run.reactions
    } reactions · ${run.plates} plate(s) · Estimated ${xmlEsc(run.runtime.label)} · ${
      run.blockingIssues ? 'Blocked by validation checks' : run.warningCount + ' warning(s)'
    }</text>`
  );
  for (let plate = 0; plate < visiblePlates; plate++) {
    const x = 64 + (plate % 3) * 365,
      y = 260 + Math.floor(plate / 3) * 180,
      n = Math.min(54, Math.max(0, run.reactions - plate * 54));
    p.push(
      `<g><rect x="${x}" y="${y}" width="336" height="156" rx="12" fill="#f8faf6" stroke="#d6ddd3" stroke-width="2"/><text x="${
        x + 12
      }" y="${y + 24}" font-family="Arial,sans-serif" font-size="14" fill="#435047">Plate ${
        plate + 1
      } · ${n}/54 positions</text>`
    );
    for (let i = 0; i < 54; i++) {
      const cx = x + 15 + (i % 9) * 34,
        cy = y + 37 + Math.floor(i / 9) * 18;
      p.push(
        `<circle cx="${cx}" cy="${cy}" r="5.5" fill="${
          i < n ? '#78aa89' : '#e8ece5'
        }" stroke="#a6b6a5"/>`
      );
    }
    p.push('</g>');
  }
  if (run.plates > visiblePlates) {
    p.push(
      `<text x="64" y="810" font-family="Arial,sans-serif" font-size="16" fill="#435047">+ ${
        run.plates - visiblePlates
      } additional reaction plates not shown</text>`
    );
  }
  p.push(
    `<text x="64" y="856" font-family="Arial,sans-serif" font-size="14" fill="#788179">Files only · No connection to or commands sent to a robot</text></svg>`
  );
  return p.join('');
}

export function notebookText(run: RunResult, dateStr?: string): string {
  const n = notebookSummary(run, dateStr);
  const L = [
    `${n.title}  (${n.date})`,
    n.meta.join(' · '),
    '',
    '| Code | Reagent | M (g/mol) | Stock (mM) | In the run | Stock needed | Stock to prepare |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const r of n.reagents) {
    L.push(`| ${r.code} | ${r.name} | ${r.mw} | ${r.stock} | ${r.use} | ${r.need} | ${r.prep} |`);
  }
  if (n.dil.length) L.push('', 'Hand dilutions: ' + n.dil.join('; '));
  L.push(
    '',
    n.warnings ? `${n.warnings} warning(s) in the validation checks.` : 'All validation checks passed.',
    'Generated by Robowski Studio. Files only; nothing is sent to the robot.'
  );
  return L.join('\n');
}

export function notebookCardSvg(run: RunResult, dateStr?: string): string {
  const n = notebookSummary(run, dateStr);
  const W = 1200;
  const cut = (x: any, k: number) => {
    x = String(x);
    return x.length > k ? x.slice(0, k - 1) + '…' : x;
  };
  const F = 'font-family="Arial,sans-serif"';
  const p: string[] = [];
  const rowH = 34;
  const y0 = 220;
  const dilLines: string[] = [];
  let line = '';
  for (const d of n.dil) {
    if ((line + d).length > 95) {
      dilLines.push(line);
      line = '';
    }
    line += (line ? '   ·   ' : '') + d;
  }
  if (line) dilLines.push(line);

  const H = y0 + rowH * (n.reagents.length + 1) + (dilLines.length ? 40 + 26 * dilLines.length : 0) + 90;
  p.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}"><rect width="100%" height="100%" fill="#fff"/><rect x="0" y="0" width="${W}" height="10" fill="#0E6F63"/>`
  );
  p.push(
    `<text x="48" y="64" ${F} font-size="30" font-weight="700" fill="#1f2a23">${xmlEsc(
      cut(n.title, 60)
    )}</text><text x="${W - 48}" y="64" ${F} font-size="18" text-anchor="end" fill="#5b655d">${xmlEsc(
      n.date
    )}</text>`
  );
  const m1 = n.meta.slice(0, 5).join('  ·  ');
  const m2 = n.meta.slice(5).join('  ·  ');
  p.push(
    `<text x="48" y="106" ${F} font-size="17" fill="#435047">${xmlEsc(m1)}</text><text x="48" y="134" ${F} font-size="17" fill="#435047">${xmlEsc(
      m2
    )}</text>`
  );
  const cols: [number, string][] = [
    [48, 'Code'],
    [112, 'Reagent'],
    [350, 'M (g/mol)'],
    [440, 'Stock (mM)'],
    [545, 'In the run'],
    [830, 'Stock needed'],
    [960, 'Stock to prepare'],
  ];
  p.push(`<rect x="36" y="${y0 - 50}" width="${W - 72}" height="40" rx="8" fill="#e8f1ee"/>`);
  for (const [x, t] of cols) {
    p.push(`<text x="${x}" y="${y0 - 24}" ${F} font-size="15" font-weight="700" fill="#315e49">${t}</text>`);
  }
  n.reagents.forEach((r, i) => {
    const y = y0 + 8 + i * rowH;
    if (i % 2) p.push(`<rect x="36" y="${y - 22}" width="${W - 72}" height="${rowH}" fill="#f7f9f6"/>`);
    p.push(
      `<text x="48" y="${y}" ${F} font-size="16" font-weight="700" fill="#0E6F63">${xmlEsc(
        r.code
      )}</text><text x="112" y="${y}" ${F} font-size="16" fill="#1f2a23">${xmlEsc(
        cut(r.name, 26)
      )}</text><text x="350" y="${y}" ${F} font-size="16" fill="#435047">${xmlEsc(
        r.mw
      )}</text><text x="440" y="${y}" ${F} font-size="16" fill="#435047">${xmlEsc(
        r.stock
      )}</text><text x="545" y="${y}" ${F} font-size="16" fill="#1f2a23">${xmlEsc(
        cut(r.use, 32)
      )}</text><text x="830" y="${y}" ${F} font-size="16" font-weight="700" fill="#1f2a23">${xmlEsc(
        r.need
      )}</text><text x="960" y="${y}" ${F} font-size="16" fill="#435047">${xmlEsc(cut(r.prep, 24))}</text>`
    );
  });
  let y = y0 + 8 + n.reagents.length * rowH + 14;
  if (dilLines.length) {
    p.push(`<text x="48" y="${y + 14}" ${F} font-size="15" font-weight="700" fill="#315e49">Hand dilutions</text>`);
    dilLines.forEach((t, i) =>
      p.push(`<text x="48" y="${y + 42 + i * 26}" ${F} font-size="15" fill="#435047">${xmlEsc(t)}</text>`)
    );
    y += 40 + 26 * dilLines.length;
  }
  p.push(
    `<text x="48" y="${H - 42}" ${F} font-size="15" fill="${
      n.warnings ? '#9a5b00' : '#2f7d5b'
    }">${
      n.warnings ? n.warnings + ' warning(s) in the validation checks' : 'All validation checks passed'
    }</text><text x="48" y="${H - 18}" ${F} font-size="13" fill="#788179">Robowski Studio · files only, nothing is sent to the robot</text></svg>`
  );
  return p.join('');
}

export async function svgToPngBytes(svg: string): Promise<Uint8Array> {
  if (typeof document === 'undefined') throw new Error('PNG rendering is available in the browser.');
  const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml;charset=utf-8' }));
  try {
    const img = new Image();
    img.src = url;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = img.naturalWidth * 2;
    canvas.height = img.naturalHeight * 2;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Could not create 2D canvas context');
    ctx.scale(2, 2);
    ctx.drawImage(img, 0, 0);
    const blob = await new Promise<Blob>((res, rej) =>
      canvas.toBlob((b) => (b ? res(b) : rej(new Error('PNG encoding failed.'))), 'image/png')
    );
    return new Uint8Array(await blob.arrayBuffer());
  } finally {
    URL.revokeObjectURL(url);
  }
}

export const notebookCardPngBytes = (run: RunResult, d?: string) => svgToPngBytes(notebookCardSvg(run, d));

export async function runCardPngBytes(run: RunResult): Promise<Uint8Array> {
  if (typeof document === 'undefined') throw new Error('PNG rendering is available in the browser.');
  const svg = runCardSvg(run);
  const url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml;charset=utf-8' }));
  try {
    const img = new Image();
    img.src = url;
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = img.naturalWidth;
    canvas.height = img.naturalHeight;
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Could not create the run-card image canvas.');
    ctx.drawImage(img, 0, 0);
    const blob = await new Promise<Blob>((resolve, reject) =>
      canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('PNG encoding failed.'))), 'image/png')
    );
    return new Uint8Array(await blob.arrayBuffer());
  } finally {
    URL.revokeObjectURL(url);
  }
}

export function runManifest(run: RunResult): any {
  return {
    app: 'Robowski Studio',
    file_format: 'robowski-input 1.02',
    generated_at: new Date().toISOString(),
    run_name: run.runName,
    mode: run.modeLabel || run.mode,
    hood: run.hood,
    reactions: run.reactions,
    vial_plates: run.plates,
    vial_volume_uL: run.vialVolume,
    pipetting_threshold_uL: run.threshold,
    dilution_factor_N: run.dilutionFactor,
    stock_leftover_mL: run.leftoverMl,
    reaction_solvent: run.reactionSolvent,
    shuffled: !!run.randomize,
    random_seed: run.randomSeed,
    deck: {
      solvent_kind: run.deck.solvent_kind,
      solvent_location: run.deck.solvent_location,
      stock_plates: run.deck.plates,
    },
    warnings: run.warningCount,
    estimated_runtime_s: {
      expected: run.runtime.seconds,
      low: run.runtime.lowSeconds,
      high: run.runtime.highSeconds,
    },
    assumptions: [
      run.runtime.calibrationNote,
      'Liquid-class limits, densities and surface-height fits are lab-supplied and should be approved by the lab owner.',
      'Solvent jar surface-height formula is an estimate until confirmed against readings.',
    ],
  };
}
