export type StepCategory =
  | 'Tautomer'
  | 'NA(N)'
  | 'NA(C)'
  | 'NA(O)'
  | 'NA(S)'
  | 'DH'
  | 'MI(N)'
  | 'MI(C)'
  | 'MI(S)'
  | 'MI(O)'
  | 'SN(N)'
  | 'SN(S)'
  | 'SN(O)'
  | 'AR'
  | 'AS(N)'
  | 'AS(O)'
  | 'AS(S)'
  | 'EA'
  | 'IS'
  | 'AO'
  | 'DC'
  | 'EL'
  | 'OX'
  | 'PC';

export interface ReactionRuleDef {
  id: string;
  stepLabel: StepCategory;
  name: string;
  description: string;
  smarts: string;
  intramolecular: boolean; // 1 reactant template applying (A.B)>>C inside same molecule
  numReactants: 1 | 2;
  acidFactor: number; // 0..1
  baseFactor: number; // 0..1
  neutralFactor: number; // 0..1
  t50: number; // °C midpoint of thermal activation
  width: number; // °C steepness
  prior: number; // intrinsic chemical feasibility 0..1
  reversible: boolean;
  kClass: 'favorable' | 'neutral' | 'unfavorable';
  thermoBonus: number; // added driving force when this step locks product / releases stable bond
  confidenceClass: ConfidenceClass;
  requiresFreeAcid?: boolean; // e.g. t-Bu cleavage gated to zero in buffered wells
  waterSensitiveReverse?: boolean; // dehydration retarded by high water%
  releasesReactiveFragment?: boolean; // second product template kept in well pool (e.g. ROH, NH3)
  releasesGas?: string | null; // e.g. 'CO2', 'Isobutylene', 'CO2 + Isobutylene'
  reactiveSiteKind?: 'amine_nuc' | 'carbon_acid' | 'thiol' | 'alcohol' | 'electrophile' | 'none';
  stericRule?: 'alpha_branching' | 'nucleophile_crowding' | 'none';
  forbidSmarts?: string[]; // molecule-level forbid patterns on product
  requireSingleSub?: boolean;
}

// Reusable SMARTS fragments
// Nucleophilic N: 1°/2° amine, NH3, or aniline; excludes amides, thioamides, guanidines/carbamates acyl-N, sulfonamides, N-N, N-C-OH
const NUC_N =
  '[NX3;H3,H2,H1;!$(N-C=[O,S]);!$(N-S=O);!$(N-N);!$(N-C-[OX2H]);!$([N+]):3]';
// Broad N including primary amidine/guanidine NH2/NH (non-acylated)
const NUC_N_BROAD =
  '[NX3;H3,H2,H1;!$(N-C(=O)-[#6,O,N]);!$(N-C(=S)-[#6,O,N]);!$(N-S=O);!$(N-N);!$(N-C-[OX2H]);!$([N+]):3]';
// Electrophilic aldehyde or ketone C=O (excludes esters, amides, acids, ureas, and trichloroacetyl acylating reagents)
const ALDEHYDE_OR_KETONE = '[CX3;!$([CX3](=O)[CX4](Cl)(Cl)Cl);$([CH1](=O)[#6]),$([CH2]=O),$(C(=O)([#6])[#6]):1]=[OX1:2]';
// Activated carbon acid C-H: dual EWG (1,3-dicarbonyl, malononitrile, cyanoester, etc.) OR single strong EWG (ketone, nitro, 2-methylazine)
const CARBON_ACID_DUAL =
  '[CX4;H2,H1;!$(C-C-[OX2H]);$(C(C=O)C=O),$(C(C#N)C#N),$(C(C=O)C#N),$(C(S(=O)=O)C=O),$(C(S(=O)=O)C#N):3]';
const CARBON_ACID_DUAL_OR_KETONE =
  '[CX4;H2,H1;!$(C-C-[OX2H]);$(C(C=O)C=O),$(C(C#N)C#N),$(C(C=O)C#N),$(C(S(=O)=O)C=O),$(C([#6;X3](=O)[#6])):3]';
const CARBON_ACID_SINGLE =
  '[CX4;H3,H2,H1;!$(C-C-[OX2H]);!$(C-[OX2H,NX3]);!$(C(C=O)C=O);!$(C(C#N)C#N);$(C([#6;X3](=O)[#6])),$(C([CX3](=O)[OX2,NX3])[a]),$(C(C#N)[#6]),$(C[NX3+](=O)[O-]),$(C-c1:[nX2]:[c,n]:[c,n]:[c,n]:[c,n]:1),$(C-c1:[c,n]:[c,n]:[nX2]:[c,n]:[c,n]:1),$(C-c1:[nX2]:[c,n]:[c,n]:[n,o,s]:1):3]';
// Heteroaromatic azole NH (imidazole, benzimidazole, pyrazole, triazole, indole)
const AZOLE_NH = '[nX3H1;r5:3]';
// Strong Michael acceptor C=C-EWG (enones, enals, acrylates, maleimides/anhydrides, nitriles, nitroalkenes, vinyl sulfones/azines)
// Excludes plain acrylamides, acrylic acids, and push-pull alkenes (β-N/O/S donor)
const MICHAEL_ACCEPTOR =
  '[CX3;!$([CX3]([NX3,OX2,SX2])):1]=[CX3;$(C([CX3H1]=O)),$(C([CX3](=O)[#6])),$(C([CX3](=O)[OX2H0][#6])),$(C([CX3](=O)[NX3][CX3]=O)),$(C([CX3](=O)[OX2][CX3]=O)),$(C(C#N)),$(C([NX3+](=O)[O-])),$(C(S(=O)=O)),$(C(c:n)):2]';
// Weak Michael acceptor (plain acrylamide, non-imide, non-push-pull)
const MICHAEL_ACCEPTOR_AMIDE =
  '[CX3;!$([CX3]([NX3,OX2,SX2])):1]=[CX3;$(C([CX3](=O)[NX3;!$(N([CX3]=O)[CX3]=O)])):2]';
// SN2 electrophilic carbon tiers: forbid tertiary (H0), gem-polyhalo, and neopentyl carbons
const SN2_FORBIDS = '!$([CX4]([F,Cl,Br,I])[F,Cl,Br,I]);!$([CX4]-[CX4;H0]([#6])([#6])[#6])';
const SN2_FAST_C = `[CX4;H3,H2;${SN2_FORBIDS};$([CH3]),$([CH2]-c),$([CH2]-[CX3]=[CX3]),$([CH2]-[CX2]#[CX2]),$([CH2]-[CX3]=O),$([CH2]-[CX2]#[NX1]):1]`;
const SN2_PRIMARY_C = `[CX4;H2;${SN2_FORBIDS};!$([CH2]-c);!$([CH2]-[CX3]=[CX3]);!$([CH2]-[CX2]#[CX2]);!$([CH2]-[CX3]=O);!$([CH2]-[CX2]#[NX1]):1]`;
const SN2_SECONDARY_C = `[CX4;H1;${SN2_FORBIDS}:1]`;
const SN2_SULFONATE_C = `[CX4;H3,H2,H1;!$([CX4]-[CX4;H0]([#6])([#6])[#6]):1][OX2][SX4](=[OX1])(=[OX1])[#6]`;
// SNAr activated aromatic carbons: strictly ortho (2 atoms) or para (4 atoms in same 6-ring) to EWG / ring N
const SNAR_EWG_OP =
  '$(c:n),$(c1:[c,n]:[c,n]:n:[c,n]:[c,n]:1),$(c:c-[NX3+](=O)[O-]),$(c1:[c,n]:[c,n]:c(-[NX3+](=O)[O-]):[c,n]:[c,n]:1),$(c:c-C#N),$(c1:[c,n]:[c,n]:c(-C#N):[c,n]:[c,n]:1),$(c:c-[CX3](=O)[#6,O]),$(c1:[c,n]:[c,n]:c(-[CX3](=O)[#6,O]):[c,n]:[c,n]:1),$(c:c-[SX4](=O)=O),$(c1:[c,n]:[c,n]:c(-[SX4](=O)=O):[c,n]:[c,n]:1)';
const SNAR_NITRO_OP =
  '$(c:c-[NX3+](=O)[O-]),$(c1:[c,n]:[c,n]:c(-[NX3+](=O)[O-]):[c,n]:[c,n]:1)';
const SNAR_DOUBLE_ACT =
  '$(c(:n):n),$(c1:n:[c,n]:c(-[NX3+](=O)[O-]):[c,n]:[c,n]:1),$(c1:c(-[NX3+](=O)[O-]):[c,n]:n:[c,n]:[c,n]:1),$(c1:n:[c,n]:[c,n]:[c,n]:c1-[NX3+](=O)[O-]),$(c1:c(-[NX3+](=O)[O-]):[c,n]:c(-[NX3+](=O)[O-]):[c,n]:[c,n]:1)';
// Activated esters (NHS, pentafluorophenyl, ortho/para-nitrophenyl)
const ACTIVATED_ESTER_O =
  '[OX2H0;$(O[NX3;r5]([CX3]=O)[CX3]=O),$(Oc1c(F)c(F)c(F)c(F)c1F),$(Oc1ccc([NX3+](=O)[O-])cc1),$(Oc1ccccc1[NX3+](=O)[O-]):4]';
const UNACTIVATED_ESTER_O =
  '[OX2H0;!$(O[NX3;r5]([CX3]=O)[CX3]=O);!$(Oc1c(F)c(F)c(F)c(F)c1F);!$(Oc1ccc([NX3+](=O)[O-])cc1);!$(Oc1ccccc1[NX3+](=O)[O-]):4]';

