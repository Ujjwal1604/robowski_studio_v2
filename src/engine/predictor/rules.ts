import { ConfidenceClass } from './types';

export type StepCategory =
  | 'Tautomer'
  | 'NA(N)'
  | 'NA(C)'
  | 'NA(O)'
  | 'NA(S)'
  | 'DH'
  | 'MI(N)'
  | 'MI(C)'
  | 'MI(S)'
  | 'MI(O)'
  | 'SN(N)'
  | 'SN(S)'
  | 'SN(O)'
  | 'AR'
  | 'AS(N)'
  | 'AS(O)'
  | 'EA'
  | 'IS'
  | 'AO'
  | 'DC'
  | 'EL'
  | 'OX'
  | 'PC';

export interface ReactionRuleDef {
  id: string;
  stepLabel: StepCategory;
  name: string;
  description: string;
  smarts: string;
  intramolecular: boolean; // 1 reactant template applying (A.B)>>C inside same molecule
  numReactants: 1 | 2;
  acidFactor: number; // 0..1
  baseFactor: number; // 0..1
  neutralFactor: number; // 0..1
  t50: number; // °C midpoint of thermal activation
  width: number; // °C steepness
  prior: number; // intrinsic chemical feasibility 0..1
  reversible: boolean;
  kClass: 'favorable' | 'neutral' | 'unfavorable';
  thermoBonus: number; // added driving force when this step locks product / releases stable bond
  confidenceClass: ConfidenceClass;
  requiresFreeAcid?: boolean; // e.g. t-Bu cleavage gated to zero in buffered wells
  waterSensitiveReverse?: boolean; // dehydration retarded by high water%
  releasesReactiveFragment?: boolean; // second product template kept in well pool (e.g. ROH, NH3)
  releasesGas?: string | null; // e.g. 'CO2', 'Isobutylene', 'CO2 + Isobutylene'
  reactiveSiteKind?: 'amine_nuc' | 'carbon_acid' | 'thiol' | 'alcohol' | 'electrophile' | 'none';
  stericRule?: 'alpha_branching' | 'nucleophile_crowding' | 'none';
  forbidSmarts?: string[]; // molecule-level forbid patterns on product
  requireSingleSub?: boolean;
}

// Reusable SMARTS fragments
// Nucleophilic N: 1°/2° amine, NH3, or aniline; excludes amides, thioamides, guanidines/carbamates acyl-N, sulfonamides, N-N, N-C-OH
